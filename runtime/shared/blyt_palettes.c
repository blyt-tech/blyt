const uint32_t *blyt_builtin_palette(uint32_t handle) {
    if (!blyt_handle_is_resource(handle))
        return 0;
    if (blyt_resource_decode_provenance(handle) != BLYT_RESOURCE_PROV_RUNTIME)
        return 0;
    switch (blyt_resource_decode_id(handle)) {
    case BLYT_PAL_ID_AURORA:
        return BLYT_PAL_AURORA;
    case BLYT_PAL_ID_VGA:
        return BLYT_PAL_VGA;
    case BLYT_PAL_ID_EGA:
        return BLYT_PAL_EGA;
    case BLYT_PAL_ID_CGA:
        return BLYT_PAL_CGA;
    default:
        return 0;
    }
}
