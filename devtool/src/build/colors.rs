//! Packer-generated named color-index constants (`C_<NAME>`), issue #203,
//! ADR-0059.
//!
//! A cart declares named swatches in `blyt.config.yaml` (`colors: {sky: 47}`);
//! the packer emits one compile-time constant per entry into `cart_colors.{h,
//! lua,rs}`, mirroring how resource `R_*` constants are emitted from assets.
//! The value is a plain palette *index* (0-255) — not a tagged handle. This is
//! the custom-palette counterpart to the SDK-shipped `BLYT_EGA_*` / `BLYT_VGA_*`
//! / `BLYT_AURORA_*` sets: built-in and custom palettes then share one model
//! (named indices, compile-time).
//!
//! `BTreeMap` iteration is sorted, so output ordering is stable across builds
//! (the build-reproducibility bar in #203).

use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;

use crate::engine::{BuildError, Task, TaskInput};

/// Generated C header (`cart_colors.h`): `#define C_<NAME> <index>` per swatch.
/// Plain integer literals (like `blyt.h`'s `BLYT_EGA_*`), so no include needed.
pub(super) fn generate_c_header(colors: &BTreeMap<String, u8>) -> String {
    let mut s = String::from("/* Generated by `blyt build` — do not edit. */\n#pragma once\n\n");
    for (name, idx) in colors {
        s.push_str(&format!(
            "#define C_{} {}\n",
            name.to_ascii_uppercase(),
            idx
        ));
    }
    s
}

/// Generated Lua module (`cart_colors.lua`): a `require`-able table mapping
/// upper-cased swatch names to their index (`local C = require("cart_colors")`
/// → `C.SKY`).
pub(super) fn generate_lua_module(colors: &BTreeMap<String, u8>) -> String {
    let mut s = String::from("-- Generated by `blyt build` — do not edit.\nreturn {\n");
    for (name, idx) in colors {
        s.push_str(&format!("    {} = {},\n", name.to_ascii_uppercase(), idx));
    }
    s.push_str("}\n");
    s
}

/// Generated Rust module (`cart_colors.rs`): `pub const C_<NAME>: u8 = <index>;`
/// per swatch, pulled in with `include!(env!("BLYT_CART_COLORS_RS"))`.
pub(super) fn generate_rust_module(colors: &BTreeMap<String, u8>) -> String {
    let mut s = String::from("// Generated by `blyt build` — do not edit.\n");
    for (name, idx) in colors {
        s.push_str(&format!(
            "pub const C_{}: u8 = {};\n",
            name.to_ascii_uppercase(),
            idx
        ));
    }
    s
}

/// Emit `blyt/c/cart_colors.h`, `blyt/lua/cart_colors.lua`, and
/// `blyt/rust/cart_colors.rs`. Registered only when the cart declares colors.
pub(super) struct GenerateColorHeadersTask {
    pub c_output: PathBuf,
    pub lua_output: PathBuf,
    pub rust_output: PathBuf,
    pub c_header: String,
    pub lua_module: String,
    pub rust_module: String,
}

impl Task for GenerateColorHeadersTask {
    fn key(&self) -> &str {
        "generate_color_headers"
    }
    fn label(&self) -> String {
        "generate cart_colors.{h,lua,rs}".to_string()
    }
    fn inputs(&self) -> Vec<TaskInput> {
        vec![
            TaskInput::Value(self.c_header.clone()),
            TaskInput::Value(self.lua_module.clone()),
            TaskInput::Value(self.rust_module.clone()),
        ]
    }
    fn outputs(&self) -> Vec<PathBuf> {
        vec![
            self.c_output.clone(),
            self.lua_output.clone(),
            self.rust_output.clone(),
        ]
    }
    fn run(&self) -> Result<(), BuildError> {
        for out in [&self.c_output, &self.lua_output, &self.rust_output] {
            if let Some(parent) = out.parent() {
                fs::create_dir_all(parent)?;
            }
        }
        fs::write(&self.c_output, &self.c_header)?;
        fs::write(&self.lua_output, &self.lua_module)?;
        fs::write(&self.rust_output, &self.rust_module)?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> BTreeMap<String, u8> {
        let mut m = BTreeMap::new();
        m.insert("sky".to_string(), 47);
        m.insert("grass".to_string(), 12);
        m
    }

    #[test]
    fn c_header_emits_uppercase_constants() {
        let h = generate_c_header(&sample());
        assert!(h.contains("#define C_SKY 47"));
        assert!(h.contains("#define C_GRASS 12"));
    }

    #[test]
    fn lua_module_emits_table_entries() {
        let m = generate_lua_module(&sample());
        assert!(m.contains("SKY = 47,"));
        assert!(m.contains("GRASS = 12,"));
        assert!(m.starts_with("-- Generated"));
    }

    #[test]
    fn rust_module_emits_typed_constants() {
        let m = generate_rust_module(&sample());
        assert!(m.contains("pub const C_SKY: u8 = 47;"));
        assert!(m.contains("pub const C_GRASS: u8 = 12;"));
    }

    #[test]
    fn ordering_is_stable_sorted() {
        // BTreeMap → grass before sky, on every build.
        let h = generate_c_header(&sample());
        assert!(h.find("C_GRASS").unwrap() < h.find("C_SKY").unwrap());
    }
}
