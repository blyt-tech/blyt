/// launch.json for any blyt cart.  All four configs use the `blyt` debug type.
/// F5 starts a debug session; Ctrl+F5 runs without a debugger.
///
/// No `cart` field: the extension detects the cart from the open project
/// (`detectAnyCart`), so one generated file works whichever file is focused and
/// regardless of the manifest `id` vs directory name (issue #55, #90).  The
/// project-dir dev modes (default WASM, `player`) launch with live reload; the
/// explicit-build `cart` / `player-cart` modes are opt-in (the user adds them).
///
/// Debug (WASM):   cart runs inside a VS Code panel (embedded browser).
/// Debug (player): cart runs in an external SDL2 window.
/// Build / Build (debug): compile the cart without launching it.
const LAUNCH_JSON: &str = "{\n\
    \x20   // Generated by `blyt setup vscode` — safe to edit or delete.\n\
    \x20   // Requires the Blyt VS Code extension (tools/vscode/).\n\
    \x20   // Debug (WASM):   F5 = debug, Ctrl+F5 = run — cart opens in a VS Code panel.\n\
    \x20   // Debug (player): F5 = debug, Ctrl+F5 = run — cart opens in an external SDL2 window.\n\
    \x20   // Build / Build (debug): compile without launching.\n\
    \x20   \"version\": \"0.2.0\",\n\
    \x20   \"configurations\": [\n\
    \x20       {\n\
    \x20           \"name\": \"Debug (WASM)\",\n\
    \x20           \"type\": \"blyt\",\n\
    \x20           \"request\": \"launch\"\n\
    \x20       },\n\
    \x20       {\n\
    \x20           \"name\": \"Debug (player)\",\n\
    \x20           \"type\": \"blyt\",\n\
    \x20           \"request\": \"launch\",\n\
    \x20           \"mode\": \"player\"\n\
    \x20       },\n\
    \x20       {\n\
    \x20           \"name\": \"Build\",\n\
    \x20           \"type\": \"blyt\",\n\
    \x20           \"request\": \"launch\",\n\
    \x20           \"mode\": \"build\"\n\
    \x20       },\n\
    \x20       {\n\
    \x20           \"name\": \"Build (debug)\",\n\
    \x20           \"type\": \"blyt\",\n\
    \x20           \"request\": \"launch\",\n\
    \x20           \"mode\": \"build-debug\"\n\
    \x20       }\n\
    \x20   ]\n\
    }\n";

/// Generate `.vscode/launch.json` for a blyt cart project so that F5 in VS
/// Code launches a debugger.  A single `blyt` config works for every cart;
/// the extension auto-detects Lua vs native and connects the right debugger.
///
/// Pass `force = true` to overwrite an existing file.
pub fn vscode(project_dir: &Path, force: bool) -> Result<(), SetupError> {
    // Validate: must be a blyt cart project.
    if !project_dir.join("blyt.info.yaml").exists() {
        return Err(err(format!(
            "blyt.info.yaml not found in {} — not a blyt cart project",
            project_dir.display()
        )));
    }

    let vscode_dir = project_dir.join(".vscode");
    let launch_path = vscode_dir.join("launch.json");

    // launch.json is precious (the user may have customised it); only (re)write
    // when absent or with --force.  The editor-scaffolding below always runs so
    // re-running `setup vscode` refreshes the generated config.
    if launch_path.exists() && !force {
        println!(
            "exists: {} (use --force to overwrite)",
            launch_path.display()
        );
    } else {
        fs::create_dir_all(&vscode_dir)
            .and_then(|_| fs::write(&launch_path, LAUNCH_JSON))
            .map_err(|e| err(format!("could not write {}: {e}", launch_path.display())))?;
        println!("wrote:  {}", launch_path.display());
    }

    write_rust_analyzer_settings(project_dir, &vscode_dir)?;
    write_lua_luarc(project_dir)?;
    // Editor codegen (compile_commands.json + Lua S decls) is shared with
    // `blyt build` and idempotent, so setup scaffolds it immediately and build
    // keeps it fresh.
    crate::build::write_editor_codegen(project_dir).map_err(|e| err(e.to_string()))?;
    Ok(())
}

/// For a cart with Lua game code, write `.luarc.json` so LuaLS picks up the
/// generated `S` state-proxy annotations under `build/blyt/lua/` — completion
/// and type-checking on `S.<buffer>[slot].<field>` (issue #48 item 1b).
///
/// Non-destructive: only written when absent (else the snippet is printed).
fn write_lua_luarc(project_dir: &Path) -> Result<(), SetupError> {
    if !project_dir.join("src/game/lua").is_dir() {
        return Ok(()); // not a Lua cart
    }

    let luarc = "{\n\
         \x20   \"$comment\": \"Generated by `blyt setup vscode` (issue #48).\",\n\
         \x20   \"runtime.version\": \"Lua 5.4\",\n\
         \x20   \"workspace.library\": [\"build/blyt/lua\"]\n\
         }\n";

    let luarc_path = project_dir.join(".luarc.json");
    if luarc_path.exists() {
        println!(
            "exists: {} — add LuaLS library manually:\n{}",
            luarc_path.display(),
            luarc
        );
        return Ok(());
    }
    fs::write(&luarc_path, luarc)
        .map_err(|e| err(format!("could not write {}: {e}", luarc_path.display())))?;
    println!("wrote:  {}", luarc_path.display());
    Ok(())
}

/// For a cart with Rust game code, write `.vscode/settings.json` telling
/// rust-analyzer the same `--config patch` that `blyt build` uses to inject the
/// SDK `blyt` crate (and any `src/lib` Rust crates).  Without it RA cannot
/// resolve `blyt = "0.1"` (it is not on crates.io) and go-to-definition into the
/// SDK crate is broken while editing (issue #48 item 1a).
///
/// settings.json is precious user state, so this only writes when the file is
/// absent; when it exists, the snippet is printed for the user to merge.
fn write_rust_analyzer_settings(project_dir: &Path, vscode_dir: &Path) -> Result<(), SetupError> {
    if !project_dir.join("src/game/rust/Cargo.toml").exists() {
        return Ok(()); // not a Rust cart — nothing to configure
    }

    // Best-effort: the RA config needs the SDK rust crate, but the primary job
    // (launch.json) already succeeded, so a missing SDK only warns.
    let rust_sdk = match find_sdk_include().and_then(|inc| find_rust_sdk(&inc)) {
        Ok(p) => p,
        Err(e) => {
            println!("note: skipped rust-analyzer config (SDK not found: {e})");
            return Ok(());
        }
    };
    let libs = discover_rust_libs(project_dir).map_err(|e| err(e.to_string()))?;

    // One `--config patch.crates-io.<name>.path="<abs>"` pair per crate, JSON
    // string-escaped (the TOML value needs literal quotes around the path).
    let mut patches: Vec<(String, std::path::PathBuf)> = vec![("blyt".to_string(), rust_sdk)];
    patches.extend(libs);
    let arg_lines = patches
        .iter()
        .map(|(name, path)| {
            format!(
                "        \"--config\",\n        \"patch.crates-io.{name}.path=\\\"{}\\\"\"",
                path.display()
            )
        })
        .collect::<Vec<_>>()
        .join(",\n");

    let settings = format!(
        "{{\n\
         \x20   // Generated by `blyt setup vscode` (issue #48).\n\
         \x20   // The blyt SDK crate is injected at build time; give rust-analyzer the\n\
         \x20   // same --config patch so go-to-definition into `blyt` resolves.\n\
         \x20   \"rust-analyzer.linkedProjects\": [\"src/game/rust/Cargo.toml\"],\n\
         \x20   \"rust-analyzer.cargo.extraArgs\": [\n\
         {arg_lines}\n\
         \x20   ]\n\
         }}\n"
    );

    let settings_path = vscode_dir.join("settings.json");
    if settings_path.exists() {
        println!(
            "exists: {} — add this rust-analyzer config manually:\n{}",
            settings_path.display(),
            settings
        );
        return Ok(());
    }
    fs::create_dir_all(vscode_dir)
        .and_then(|_| fs::write(&settings_path, &settings))
        .map_err(|e| err(format!("could not write {}: {e}", settings_path.display())))?;
    println!("wrote:  {}", settings_path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::LAUNCH_JSON;

    /// Strip whole-line `//` comments so the JSONC template parses as JSON.
    fn parse_launch_json() -> serde_json::Value {
        let stripped: String = LAUNCH_JSON
            .lines()
            .filter(|l| !l.trim_start().starts_with("//"))
            .collect::<Vec<_>>()
            .join("\n");
        serde_json::from_str(&stripped).expect("generated launch.json must be valid JSON")
    }

    /// The generated launch.json must omit the `cart` field in every config so
    /// the extension resolves the cart from the open project (`detectAnyCart`),
    /// not a hardcoded path baked at setup time (#55, #90).
    #[test]
    fn generated_launch_json_omits_cart_field() {
        let v = parse_launch_json();
        let configs = v["configurations"]
            .as_array()
            .expect("configurations array");
        assert!(!configs.is_empty(), "expected at least one configuration");
        for c in configs {
            assert!(
                c.get("cart").is_none(),
                "config {:?} must not pin a `cart` field — rely on detectAnyCart",
                c["name"]
            );
        }
    }

    /// Every generated `mode` must be a current taxonomy value (#90 renamed
    /// `native` → `player`); a stale `native` would silently fall through to the
    /// WASM path since the extension only treats player/player-cart as native.
    #[test]
    fn generated_launch_json_uses_current_modes() {
        let v = parse_launch_json();
        // Mirrors the enum in tools/vscode/package.json.
        const VALID: [&str; 5] = ["player", "cart", "player-cart", "build", "build-debug"];
        let configs = v["configurations"].as_array().unwrap();
        for c in configs {
            if let Some(mode) = c.get("mode") {
                let mode = mode.as_str().expect("mode is a string");
                assert!(
                    VALID.contains(&mode),
                    "config {:?} uses unknown mode {mode:?}",
                    c["name"]
                );
            }
        }
        // The default (WASM dev) config carries no mode at all.
        assert!(
            configs.iter().any(|c| c.get("mode").is_none()),
            "expected a default (no-mode) WASM config"
        );
        // Guard the specific #90 regression: the old `native` value is gone.
        assert!(
            !LAUNCH_JSON.contains("\"native\""),
            "stale `native` mode in generated launch.json — rename to `player`"
        );
    }
}
